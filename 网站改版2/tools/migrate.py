def build_front_matter(zone, anchor, title, desc, keywords, order, internal=False):
    lines = ["---"]
    lines.append("title: %s" % title)
    if desc:
        lines.append("desc: %s" % desc)
    lines.append("zone: %s" % zone)
    lines.append("anchor: %s" % anchor)
    lines.append("order: %d" % order)
    if keywords:
        lines.append("keywords: %s" % ", ".join(keywords))
    if internal:
        lines.append("internal: true")
    lines.append("---")
    return "\n".join(lines) + "\n\n"


def main():
    done = 0
    skipped = 0
    missing = []

    # ---- 1. 给已知的子板块 md 加 front-matter ----
    order_by_zone = {}
    for rel, zone, anchor, title, desc in BLOCKS:
        order_by_zone.setdefault(zone, []).append((rel, anchor, title, desc))

    for zone, blocks in order_by_zone.items():
        for i, (rel, anchor, title, desc) in enumerate(blocks, start=1):
            path = os.path.join(SRC, rel.replace("/", os.sep))
            if not os.path.exists(path):
                missing.append(rel)
                continue

            raw = read_text(path)
            meta, body = parse_front_matter(raw)
            if meta.get("title"):
                skipped += 1
                continue

            kw = [k for k in EXTRA_KEYWORDS.get(title, []) if k != title]
            fm = build_front_matter(zone, anchor, title, desc, kw, i)
            write_text(path, fm + body.lstrip("\n"))
            done += 1
            print("  + %-46s -> %s/%s" % (rel, zone, anchor))

    # ---- 2. 内部文档标记 ----
    for rel in INTERNAL_DOCS:
        path = os.path.join(SRC, rel.replace("/", os.sep))
        if not os.path.exists(path):
            continue
        raw = read_text(path)
        meta, body = parse_front_matter(raw)
        if meta.get("internal"):
            continue
        fm = build_front_matter("internal", "", rel.split("/")[-1][:-3], "", [], 999,
                                 internal=True)
        write_text(path, fm + body.lstrip("\n"))
        done += 1
        print("  - %-46s -> internal" % rel)

    print("\n已写入 front-matter：%d 个，跳过（已有）：%d 个" % (done, skipped))
    if missing:
        print("缺失文件：")
        for m in missing:
            print("  !", m)


if __name__ == "__main__":
    main()
